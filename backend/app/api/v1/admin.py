import uuid
from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, status, Query
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy import select, func, delete
from sqlalchemy.orm import selectinload

from app.db.session import get_db
from app.models.domain import User, UserRole, Project, ProjectMember, AuditLog
from app.schemas.auth import UserResponse, AdminUserCreate
from app.core.security import get_password_hash
from app.core.rbac import require_roles
from pydantic import BaseModel, EmailStr

router = APIRouter(prefix="/admin", tags=["Admin Management"])


class AdminUserListItem(BaseModel):
    id: uuid.UUID
    email: str
    full_name: str
    role: UserRole
    is_active: bool
    is_approved: bool
    assigned_project_count: int
    assigned_projects: List[dict]
    created_at: str

    model_config = {"from_attributes": True}


class UserApprovalRequest(BaseModel):
    role: Optional[UserRole] = None
    project_ids: Optional[List[uuid.UUID]] = None


@router.get("/users", response_model=List[AdminUserListItem])
async def list_all_users(
    db: AsyncSession = Depends(get_db),
    current_user: User = require_roles([UserRole.ADMIN])
):
    """List all registered platform users with their roles, approval status, and project assignments (Admin only)."""
    stmt = (
        select(User)
        .options(selectinload(User.memberships).selectinload(ProjectMember.project))
        .order_by(User.created_at.desc())
    )
    users = (await db.execute(stmt)).scalars().all()

    results = []
    for u in users:
        assigned = [
            {"id": str(m.project_id), "name": m.project.name if m.project else "Unknown", "role": m.role.value}
            for m in u.memberships if m.project
        ]
        results.append(AdminUserListItem(
            id=u.id,
            email=u.email,
            full_name=u.full_name,
            role=u.role,
            is_active=u.is_active,
            is_approved=getattr(u, "is_approved", True),
            assigned_project_count=len(assigned),
            assigned_projects=assigned,
            created_at=u.created_at.isoformat()
        ))
    return results


@router.get("/users/pending", response_model=List[AdminUserListItem])
async def list_pending_users(
    db: AsyncSession = Depends(get_db),
    current_user: User = require_roles([UserRole.ADMIN])
):
    """List all self-registered users awaiting administrator approval."""
    stmt = (
        select(User)
        .where(User.is_approved == False)
        .order_by(User.created_at.desc())
    )
    users = (await db.execute(stmt)).scalars().all()
    return [
        AdminUserListItem(
            id=u.id,
            email=u.email,
            full_name=u.full_name,
            role=u.role,
            is_active=u.is_active,
            is_approved=u.is_approved,
            assigned_project_count=0,
            assigned_projects=[],
            created_at=u.created_at.isoformat()
        )
        for u in users
    ]


@router.post("/users", response_model=AdminUserListItem, status_code=status.HTTP_201_CREATED)
async def generate_user_id(
    payload: AdminUserCreate,
    db: AsyncSession = Depends(get_db),
    current_user: User = require_roles([UserRole.ADMIN])
):
    """Directly generate and provision a Tester, Viewer, or Developer account (Admin only). Account is immediately approved."""
    # Check if user already exists
    stmt = select(User).where(User.email == payload.email)
    existing = (await db.execute(stmt)).scalar_one_or_none()
    if existing:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"An account with email '{payload.email}' already exists."
        )

    hashed_pwd = get_password_hash(payload.password)
    new_user = User(
        email=payload.email,
        hashed_password=hashed_pwd,
        full_name=payload.full_name,
        role=payload.role,
        is_active=True,
        is_approved=True  # Generated by admin, directly approved
    )
    db.add(new_user)
    await db.flush()

    # Assign to initial projects if specified
    assigned = []
    if payload.project_ids:
        for pid in payload.project_ids:
            proj = (await db.execute(select(Project).where(Project.id == pid))).scalar_one_or_none()
            if proj:
                member = ProjectMember(project_id=pid, user_id=new_user.id, role=payload.role)
                db.add(member)
                assigned.append({"id": str(pid), "name": proj.name, "role": payload.role.value})

    audit_entry = AuditLog(
        actor_id=current_user.id,
        action="ADMIN_GENERATED_USER",
        resource_type="USER",
        resource_id=str(new_user.id),
        details={"email": new_user.email, "role": new_user.role.value}
    )
    db.add(audit_entry)
    await db.commit()
    await db.refresh(new_user)

    return AdminUserListItem(
        id=new_user.id,
        email=new_user.email,
        full_name=new_user.full_name,
        role=new_user.role,
        is_active=new_user.is_active,
        is_approved=new_user.is_approved,
        assigned_project_count=len(assigned),
        assigned_projects=assigned,
        created_at=new_user.created_at.isoformat()
    )


@router.post("/users/{user_id}/approve", response_model=AdminUserListItem)
async def approve_user(
    user_id: uuid.UUID,
    payload: Optional[UserApprovalRequest] = None,
    db: AsyncSession = Depends(get_db),
    current_user: User = require_roles([UserRole.ADMIN])
):
    """Approve a self-registered user and assign their official role and repositories (Admin only)."""
    target = (await db.execute(select(User).where(User.id == user_id))).scalar_one_or_none()
    if not target:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="User not found")

    target.is_approved = True
    target.is_active = True
    if payload and payload.role:
        target.role = payload.role

    assigned = []
    if payload and payload.project_ids:
        for pid in payload.project_ids:
            proj = (await db.execute(select(Project).where(Project.id == pid))).scalar_one_or_none()
            if proj:
                # Check existing membership
                stmt_m = select(ProjectMember).where(ProjectMember.project_id == pid, ProjectMember.user_id == target.id)
                ex_m = (await db.execute(stmt_m)).scalar_one_or_none()
                if not ex_m:
                    db.add(ProjectMember(project_id=pid, user_id=target.id, role=target.role))
                assigned.append({"id": str(pid), "name": proj.name, "role": target.role.value})

    audit_entry = AuditLog(
        actor_id=current_user.id,
        action="ADMIN_APPROVED_USER",
        resource_type="USER",
        resource_id=str(target.id),
        details={"email": target.email, "role": target.role.value}
    )
    db.add(audit_entry)
    await db.commit()
    await db.refresh(target)

    return AdminUserListItem(
        id=target.id,
        email=target.email,
        full_name=target.full_name,
        role=target.role,
        is_active=target.is_active,
        is_approved=target.is_approved,
        assigned_project_count=len(assigned),
        assigned_projects=assigned,
        created_at=target.created_at.isoformat()
    )


@router.post("/users/{user_id}/reject", status_code=status.HTTP_200_OK)
async def reject_user(
    user_id: uuid.UUID,
    db: AsyncSession = Depends(get_db),
    current_user: User = require_roles([UserRole.ADMIN])
):
    """Reject and delete a pending user registration (Admin only)."""
    target = (await db.execute(select(User).where(User.id == user_id))).scalar_one_or_none()
    if not target:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="User not found")

    if target.role == UserRole.ADMIN or target.email == "admin@astra.local":
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Cannot reject superadmin user.")

    audit_entry = AuditLog(
        actor_id=current_user.id,
        action="ADMIN_REJECTED_USER",
        resource_type="USER",
        resource_id=str(target.id),
        details={"email": target.email}
    )
    db.add(audit_entry)
    await db.delete(target)
    await db.commit()
    return {"message": f"User {target.email} registration rejected and removed."}


@router.delete("/users/{user_id}", status_code=status.HTTP_204_NO_CONTENT)
async def delete_user(
    user_id: uuid.UUID,
    db: AsyncSession = Depends(get_db),
    current_user: User = require_roles([UserRole.ADMIN])
):
    """Permanently delete a user account (Admin only)."""
    if user_id == current_user.id:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Cannot delete your own active admin account.")

    target = (await db.execute(select(User).where(User.id == user_id))).scalar_one_or_none()
    if not target:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="User not found")

    if target.email == "admin@astra.local":
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Cannot delete default admin.")

    audit_entry = AuditLog(
        actor_id=current_user.id,
        action="ADMIN_DELETED_USER",
        resource_type="USER",
        resource_id=str(target.id),
        details={"email": target.email}
    )
    db.add(audit_entry)
    await db.delete(target)
    await db.commit()
    return None
