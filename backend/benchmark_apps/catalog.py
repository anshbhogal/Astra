from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Dict, List, Optional, Set


class DefectSeverity(str, Enum):
    CRITICAL = "CRITICAL"
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"


class DefectCategory(str, Enum):
    AUTHENTICATION = "AUTHENTICATION"
    AUTHORIZATION = "AUTHORIZATION"
    VALIDATION_BOUNDARY = "VALIDATION_BOUNDARY"
    DATA_INTEGRITY = "DATA_INTEGRITY"
    BUSINESS_LOGIC = "BUSINESS_LOGIC"
    STATE_MACHINE = "STATE_MACHINE"
    CONCURRENCY_RACE = "CONCURRENCY_RACE"
    INJECTION_SECURITY = "INJECTION_SECURITY"
    PERFORMANCE_SLA = "PERFORMANCE_SLA"
    ERROR_HANDLING_CRASH = "ERROR_HANDLING_CRASH"


class BenchmarkExecutionProfile(str, Enum):
    IN_PROCESS_DETERMINISTIC = "IN_PROCESS_DETERMINISTIC"
    CONCURRENT_TRANSACTIONAL = "CONCURRENT_TRANSACTIONAL"


@dataclass(frozen=True)
class GroundTruthBug:
    bug_id: str
    service: str  # "auth", "ecommerce", "student", "banking"
    endpoint: str
    method: str
    category: DefectCategory
    severity: DefectSeverity
    description: str
    precondition: Dict[str, Any]
    trigger_input: Dict[str, Any]
    expected_behavior: Dict[str, Any]
    buggy_behavior: Dict[str, Any]
    detection_signatures: List[str]
    allowed_test_types: List[str]
    execution_profile: BenchmarkExecutionProfile = BenchmarkExecutionProfile.IN_PROCESS_DETERMINISTIC
    oracle_version: str = "oracle-v1.0"


@dataclass(frozen=True)
class NegativeControl:
    control_id: str
    service: str
    endpoint: str
    method: str
    control_type: str  # "VALID_HAPPY_PATH", "LEGITIMATE_BOUNDARY", "EXPECTED_ERROR", "UNRELATED_ENDPOINT"
    input_data: Dict[str, Any]
    expected_status: int
    description: str


