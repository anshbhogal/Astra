    @classmethod
    def get_bug(cls, bug_id: str) -> Optional[GroundTruthBug]:
        return cls.BUGS.get(bug_id)

    @classmethod
    def get_bugs_for_service(cls, service: str) -> List[GroundTruthBug]:
        return [b for b in cls.BUGS.values() if b.service == service]

    @classmethod
    def get_controls_for_service(cls, service: str) -> List[NegativeControl]:
        return [c for c in cls.CONTROLS.values() if c.service == service]

    @classmethod
    def get_all_bugs(cls) -> List[GroundTruthBug]:
        return list(cls.BUGS.values())

    @classmethod
    def get_all_controls(cls) -> List[NegativeControl]:
        return list(cls.CONTROLS.values())
